	/** 29 種位移（dy、dx 由小到大編號，|d|≤3），與 game.js 的 MV 相同。 */
	private static function moves() {
		$mv = [];
		for($dy = -3; $dy <= 3; $dy++) {
			for($dx = -3; $dx <= 3; $dx++) {
				if($dx * $dx + $dy * $dy <= 9) {
					$mv[] = [$dx, $dy];
				}
			}
		}
		return $mv;
	}

	private static function rnd(&$s) {
		$s = ($s * 48271) % 2147483647;
		return $s;
	}

	/** 一顆子彈放進 $out：[x, y, vx, vy, 半徑]。 */
	private static function shoot(&$out, $cx, $cy, $a, $spd, $rad, $r) {
		$a = (($a % 360) + 360) % 360;
		$c = self::COS[$a];
		$sn = self::SIN[$a];
		$out[] = [$cx * 256 + intdiv($c * $rad, 4), $cy * 256 + intdiv($sn * $rad, 4), intdiv($c * $spd, 1024), intdiv($sn * $spd, 1024), $r];
	}

	/** 這一步型態 $p 要發射的子彈（與 game.js 的 ring／spiral／aimed／rain／petal 逐行對應）。 */
	private static function fire(&$out, &$s, $p, $u, $lv, $boss, $stage, $ex, $ey, $px, $py) {
		if($p === 0) {
			$iv = max(34, 64 - 2 * $lv);
			if($boss) {
				$iv = intdiv($iv * 7, 5);
			}
			if($u % $iv !== 0) {
				return;
			}
			$k = intdiv($u, $iv);
			$n = min(34, 16 + $lv);
			$a0 = ($k * 13) % 360;
			$spd = 300 + 11 * $lv;
			for($j = 0; $j < $n; $j++) {
				self::shoot($out, $ex, $ey, $a0 + intdiv(360 * $j, $n), $spd, 10, 3);
			}
		} elseif($p === 1) {
			$iv = $boss ? 9 : 6;
			if($u % $iv !== 0) {
				return;
			}
			$arms = $lv < 8 ? 2 : ($lv < 14 ? 3 : 4);
			$spd = 330 + 9 * $lv;
			$base = ($u * 2) % 360;
			if($stage % 2 === 1) {
				$base = 360 - $base;
			}
			for($j = 0; $j < $arms; $j++) {
				self::shoot($out, $ex, $ey, $base + intdiv(360 * $j, $arms), $spd, 8, 3);
			}
		} elseif($p === 2) {
			$iv = max(24, 52 - $lv);
			if($boss) {
				$iv = intdiv($iv * 7, 5);
			}
			$m = $u % $iv;
			$shots = 3 + ($lv >= 10 ? 2 : 0);
			if($m % 5 !== 0 || $m >= 5 * $shots) {
				return;
			}
			$fan = $lv < 5 ? 1 : ($lv < 12 ? 3 : 5);
			$spd = 420 + 13 * $lv;
			$dx = $px - $ex;
			$dy = $py - $ey;
			$len = (int)floor(sqrt($dx * $dx + $dy * $dy));
			if($len < 1) {
				$len = 1;
			}
			$vx = intdiv($dx * $spd, $len);
			$vy = intdiv($dy * $spd, $len);
			for($j = 0; $j < $fan; $j++) {
				$a = ((((2 * $j - ($fan - 1)) * 7) % 360) + 360) % 360;
				$c = self::COS[$a];
				$sn = self::SIN[$a];
				$out[] = [$ex * 256, $ey * 256, intdiv($vx * $c - $vy * $sn, 1024), intdiv($vx * $sn + $vy * $c, 1024), 4];
			}
		} elseif($p === 3) {
			$iv = $boss ? 5 : 4;
			if($u % $iv !== 0) {
				return;
			}
			$c = 1 + ($lv >= 7 ? 1 : 0) + ($lv >= 13 ? 1 : 0);
			for($i = 0; $i < $c; $i++) {
				$x = self::rnd($s) % 360;
				$vx = (self::rnd($s) % 81) - 40;
				$vy = 380 + (self::rnd($s) % 220) + 8 * $lv;
				$out[] = [$x * 256, -6 * 256, $vx, $vy, 3];
			}
		} else {
			$iv = max(52, 110 - 3 * $lv);
			if($boss) {
				$iv = intdiv($iv * 7, 5);
			}
			if($u % $iv !== 0) {
				return;
			}
			$cx = 40 + (self::rnd($s) % 280);
			$cy = 30 + (self::rnd($s) % 90);
			$a0 = self::rnd($s) % 72;
			$half = 2 + min(2, intdiv($lv, 6));
			$spd = 260 + 8 * $lv;
			for($pp = 0; $pp < 5; $pp++) {
				for($k = -$half; $k <= $half; $k++) {
					self::shoot($out, $cx, $cy, $a0 + 72 * $pp + 6 * $k, $spd + ($half + 1 - abs($k)) * 55, 6, 3);
				}
			}
		}
	}

	public static function verify($seed, array $data) {
		if((string)($data['v'] ?? '') !== (string)self::RULE) {
			return ['ok' => 0, 'reason' => '游戏已更新，请重新整理页面后再玩'];
		}
		$ts = (string)($data['ticks'] ?? '');
		$sc = (string)($data['score'] ?? '');
		if(!preg_match('/^[1-9][0-9]{0,4}$/', $ts) || (int)$ts > self::MAXT) {
			return ['ok' => 0, 'reason' => '步数不合理'];
		}
		if(!preg_match('/^(0|[1-9][0-9]{0,8})$/', $sc)) {
			return ['ok' => 0, 'reason' => '分数格式错误'];
		}
		$ticks = (int)$ts;
		$claim = (int)$sc;
		$raw = (string)($data['pos'] ?? '');
		if(strlen($raw) < 1 || strlen($raw) > 120000) {
			return ['ok' => 0, 'reason' => '位置纪录格式错误'];
		}
		// 解位置紀錄：逐段 "字母＋次數"，整串都要被吃完，總步數剛好 ticks
		$mv = self::moves();
		$cnt = preg_match_all('/([a-zA-C])([1-9][0-9]{0,4})?/', $raw, $mm, PREG_SET_ORDER);
		$used = 0;
		$dxs = [];
		$dys = [];
		foreach($mm as $m) {
			$used += strlen($m[0]);
			$c = isset($m[2]) && $m[2] !== '' ? (int)$m[2] : 1;
			$d = $mv[strpos(self::ALPHA, $m[1])];
			if(count($dxs) + $c > $ticks) {
				return ['ok' => 0, 'reason' => '位置纪录步数与成绩不符'];
			}
			for($i = 0; $i < $c; $i++) {
				$dxs[] = $d[0];
				$dys[] = $d[1];
			}
		}
		if(!$cnt || $used !== strlen($raw)) {
			return ['ok' => 0, 'reason' => '位置纪录格式错误'];
		}
		if(count($dxs) !== $ticks) {
			return ['ok' => 0, 'reason' => '位置纪录步数与成绩不符'];
		}

		$COS = self::COS;
		$SIN = self::SIN;
		$s = (int)$seed;
		$px = self::X0;
		$py = self::Y0;
		$lives = self::LIVES;
		$inv = 0;
		$score = 0;
		$graze = 0;
		$n = 0;
		$bx = [];
		$by = [];
		$bvx = [];
		$bvy = [];
		$br = [];
		$bg = [];
		$p1 = 0;
		$p2 = -1;
		$stage = 0;
		$boss = false;
		$end = 0;
		$FP = self::FP;
		$LO = -24 * $FP;
		$HIX = (self::W + 24) * $FP;
		$HIY = (self::H + 24) * $FP;
		$G = self::GRAZE_R * $FP;
		$G2 = $G * $G;
		$HR = self::HIT_R;
		$MAXB = self::MAXB;
		for($t = 1; $t <= $ticks; $t++) {
			$px += $dxs[$t - 1];
			$py += $dys[$t - 1];
			if($px < self::MINX || $px > self::MAXX || $py < self::MINY || $py > self::MAXY) {
				return ['ok' => 0, 'reason' => '自机位置超出范围'];
			}
			$u = ($t - 1) % self::STAGE;
			$lv = intdiv($t - 1, self::STAGE);
			$ex = 180 + intdiv($SIN[($t * 2) % 360] * 100, 1024);
			$ey = 70;
			if($u === 0) {
				$stage = $lv;
				$boss = $lv % 4 === 3;
				$p1 = self::rnd($s) % 5;
				$p2 = -1;
				if($boss) {
					$p2 = ($p1 + 1 + (self::rnd($s) % 4)) % 5;
				}
			}
			$new = [];
			self::fire($new, $s, $p1, $u, $lv, $boss, $stage, $ex, $ey, $px, $py);
			if($p2 >= 0) {
				self::fire($new, $s, $p2, $u, $lv, $boss, $stage, $ex, $ey, $px, $py);
			}
			foreach($new as $b) {
				if($n < $MAXB) {
					$bx[$n] = $b[0];
					$by[$n] = $b[1];
					$bvx[$n] = $b[2];
					$bvy[$n] = $b[3];
					$br[$n] = $b[4];
					$bg[$n] = 0;
					$n++;
				}
			}
			$pxf = $px * $FP;
			$pyf = $py * $FP;
			$hitnow = false;
			for($i = $n - 1; $i >= 0; $i--) {
				$x = $bx[$i] + $bvx[$i];
				$y = $by[$i] + $bvy[$i];
				if($x < $LO || $x > $HIX || $y < $LO || $y > $HIY) {
					$n--;
					if($i !== $n) {
						$bx[$i] = $bx[$n];
						$by[$i] = $by[$n];
						$bvx[$i] = $bvx[$n];
						$bvy[$i] = $bvy[$n];
						$br[$i] = $br[$n];
						$bg[$i] = $bg[$n];
					}
					continue;
				}
				$bx[$i] = $x;
				$by[$i] = $y;
				$ddx = $x - $pxf;
				if($ddx > $G || $ddx < -$G) {
					continue;
				}
				$ddy = $y - $pyf;
				if($ddy > $G || $ddy < -$G) {
					continue;
				}
				$d2 = $ddx * $ddx + $ddy * $ddy;
				if($bg[$i] === 0 && $d2 <= $G2) {
					$bg[$i] = 1;
					$graze++;
					$score += 5;
				}
				$hr = ($HR + $br[$i]) * $FP;
				if($d2 <= $hr * $hr) {
					$hitnow = true;
				}
			}
			$was = $inv;
			if($inv > 0) {
				$inv--;
			}
			if($hitnow && $was === 0) {
				$lives--;
				$n = 0;
				$inv = self::INV;
				if($lives === 0) {
					$end = $t;
					break;
				}
			}
			if($t % 60 === 0) {
				$score += 10;
			}
			if($t % self::STAGE === 0) {
				$score += (intdiv($t, self::STAGE) - 1) % 4 === 3 ? 1000 : 500;
			}
			if($t === self::MAXT) {
				$end = $t;
				break;
			}
		}
		if($end !== $ticks) {
			return ['ok' => 0, 'reason' => '重播结果与成绩不符'];
		}
		if($claim !== $score) {
			return ['ok' => 0, 'reason' => '重播分数与成绩不符'];
		}
		$sec = intdiv($ticks, 60);
		return [
			'ok' => 1,
			'score' => $score,
			'minms' => intdiv($ticks * 1000, 60),
			'stats' => ['存活' => intdiv($sec, 60).':'.sprintf('%02d', $sec % 60), '擦弹' => $graze, '阶段' => intdiv($ticks - 1, self::STAGE) + 1],
		];
	}
